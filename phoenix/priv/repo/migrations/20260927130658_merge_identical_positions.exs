defmodule App.Repo.Migrations.MergeIdenticalPositions do
  @moduledoc """
  Posts get an authorised strength, and identical posts (same title, unit,
  grade and reporting line — e.g. ten "Rifleman · A Company, 1 Bn · OR-3")
  are merged into one post whose strength is how many there were
  (user's decision, docs/design/roadmap.md). Every assignment on a copy,
  current or past, moves to the kept post (the oldest); posts that reported
  to a copy report to the kept post; then the copies are deleted and a
  unique index keeps new duplicates out.

  Generated by `mix ash_postgres.generate_migrations`, then edited: the
  merge must run between adding the column and creating the index.
  Repeated until nothing merges, because re-pointing `reports_to_id` can
  make further posts identical. `down` restores the column and index
  only; merged copies are not split again.
  """

