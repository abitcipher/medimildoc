          SELECT id,
                 first_value(id) OVER w AS keep,
                 count(*) OVER w AS copies
          FROM positions
          WINDOW w AS (PARTITION BY title, organization_id, authorised_grade, reports_to_id
                       ORDER BY inserted_at, id
                       ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING);

        SELECT count(*) INTO merged FROM position_merge WHERE id <> keep;
        EXIT WHEN merged = 0;

        UPDATE assignments a SET position_id = m.keep
          FROM position_merge m WHERE a.position_id = m.id AND m.id <> m.keep;
