defmodule AppWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :app

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  #
  # same_site: "None" in prod only (config/prod.exs sets
  # session_same_site, dev/test default to "Lax") —  the
  # embedded /sheets LiveView lives inside Google's third-party sandboxed
  # iframe, and Chrome drops SameSite=Lax cookies there entirely, failing
  # every WebSocket join's CSRF check and forcing phoenix_live_view's
  # client into a permanent reload loop (confirmed live). Browsers drop a
  # SameSite=None cookie without `Secure`, so it is set explicitly with it
  # Plug's scheme-based auto-detection only adds it
  # over HTTPS, and a release on plain http://localhost (the local copy of
  # staging; force_ssl excludes localhost) got no cookie at all and looped
  # the same way. Browsers accept Secure cookies on http://localhost; the
  # VPS is HTTPS anyway. "Lax" in dev needs neither.
  @session_options [
    store: :cookie,
    key: "_app_key",
    signing_salt: "qeN7aBX5",
    same_site: Application.compile_env(:app, :session_same_site, "Lax"),
    secure: Application.compile_env(:app, :session_same_site, "Lax") == "None"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    # The peer and X-Forwarded-For give the client address of access
    # events (AppWeb.ClientIp).
    websocket: [connect_info: [:peer_data, :x_headers, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :app,
    gzip: not code_reloading?,
    only: AppWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :app
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug AppWeb.Router
end
