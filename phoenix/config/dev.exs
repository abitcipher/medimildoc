# Google OAuth for the standalone forms UI (App.Accounts.
# User — read from env so a real Google Cloud OAuth client can be
# plugged in locally without touching code; the placeholders let the app
# boot and the sign-in page render, but the actual Google redirect will
# fail (invalid client) until real values are set. Get real ones from
# https://console.cloud.google.com (APIs & Services -> Credentials).
#
# GOOGLE_REDIRECT_URI is the *base* AshAuthentication.Strategy.OAuth2
# appends "user/google/callback" onto (by URI-joining onto its `.path`) —
# not the full callback URL itself. Two things confirmed live against the
# Docker release, both required:
#   1. It needs a trailing "/", or `URI.path` comes back `nil` and it
#      crashes (`String.ends_with?(nil, ...)`) — matches the upstream DSL
#      doc's own example (`redirect_uri "https://my.app/"`).
#   2. It must include this router's "/auth" prefix (`auth_routes
#      AuthController, App.Accounts.User, path: "/auth"`) — otherwise the
#      built redirect_uri comes out as ".../user/google/callback", missing
#      "/auth", and won't match the actual route or what you register in
#      Google Cloud Console.
# So the value below must resolve to exactly this deploy's
# http://localhost:4000/auth/user/google/callback once the suffix is
# appended — i.e. the base is .../auth/, not just the bare host.
config :app,
  google_client_id: System.get_env("GOOGLE_CLIENT_ID", "dev-placeholder-client-id"),
  google_client_secret: System.get_env("GOOGLE_CLIENT_SECRET", "dev-placeholder-client-secret"),
  google_redirect_uri: System.get_env("GOOGLE_REDIRECT_URI", "http://localhost:4000/auth/")

