defmodule App.Repo.Migrations.AddPersonId do
  @moduledoc """
  Adds `people.person_id`. Hand-edited after
  `mix ash_postgres.generate_migrations` — the autogenerated version
  added the column straight as `null: false`, which fails outright on
  any environment where `people` already has rows (confirmed:
  production has one). Expand-contract instead: add nullable, backfill
  every existing row with a real generated code (not a placeholder —
  these are meant to be usable identifiers, not filler), THEN tighten
  to `NOT NULL` + the unique index.

  Backfill is plain SQL, not `App.People.PersonId`/Ash — a migration
  shouldn't depend on the application's current code compiling/
  behaving a particular way; the alphabet/shape rules are inlined here
  once, deliberately duplicating `App.People.PersonId`'s Elixir
  implementation rather than calling it.
  """

  use Ecto.Migration

  @vowels ~w(A E I O U)
  @consonants ~w(B C D F G H J K L M N P Q R S T V W X Y Z)

  def up do
    alter table(:people) do
      add :person_id, :text
    end

    # Ecto.Migration queues DDL and only actually runs it against the DB
    # at a flush point — without this, the raw SELECT in
    # backfill_person_ids/0 below sees the pre-`alter` schema and fails
    # with "column person_id does not exist" (confirmed live).
    flush()

    backfill_person_ids()

    alter table(:people) do
      modify :person_id, :text, null: false
    end

    create unique_index(:people, [:person_id], name: "people_unique_person_id_index")
  end

  def down do
    drop_if_exists unique_index(:people, [:person_id], name: "people_unique_person_id_index")

    alter table(:people) do
      remove :person_id
    end
  end

  defp backfill_person_ids do
    {:ok, %{rows: rows}} = repo().query("SELECT id FROM people WHERE person_id IS NULL", [])

    Enum.reduce(rows, MapSet.new(), fn [id], used ->
      code = unique_code(used)
      repo().query!("UPDATE people SET person_id = $1 WHERE id = $2", [code, id])
      MapSet.put(used, code)
    end)
  end

  # Same shape rules as App.People.PersonId.generate/0 (12 chars,
  # alternating consonant/vowel, no letter more than twice) — collision
  # against `used` is only possible within this one backfill run
  # (nothing else could have written person_id concurrently, the column
  # doesn't exist as a target for the app yet), so a bounded retry
  # against an in-memory set is enough here, unlike the app-level
  # generate_unique/0 which checks the live DB.
  defp unique_code(used, attempts_left \\ 20)

  defp unique_code(_used, 0) do
    raise "AddPersonId migration: could not generate a unique person_id during backfill"
  end

  defp unique_code(used, attempts_left) do
    code = generate_code()
    if MapSet.member?(used, code), do: unique_code(used, attempts_left - 1), else: code
  end

  defp generate_code do
    starts_with_vowel? = Enum.random([true, false])

    {chars, _counts} =
      Enum.reduce(1..12, {[], %{}}, fn i, {acc, counts} ->
        odd_position? = rem(i, 2) == 1
        is_vowel? = odd_position? == starts_with_vowel?
        pool = if is_vowel?, do: @vowels, else: @consonants
        available = Enum.reject(pool, &(Map.get(counts, &1, 0) >= 2))
        char = Enum.random(available)
        {[char | acc], Map.update(counts, char, 1, &(&1 + 1))}
      end)

    chars |> Enum.reverse() |> Enum.join()
  end
end
