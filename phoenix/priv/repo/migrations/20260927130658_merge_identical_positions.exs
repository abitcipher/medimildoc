          FROM (SELECT DISTINCT keep, copies FROM position_merge WHERE copies > 1) m
          WHERE p.id = m.keep;
        DELETE FROM positions p USING position_merge m WHERE p.id = m.id AND m.id <> m.keep;

        DROP TABLE position_merge;
      END LOOP;
    END $$;
    """)

